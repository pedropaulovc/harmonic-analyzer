def is_native_operation_field(key):
    # "fixture" and "fixtureHeadPixel" are observed source fields, not fits;
    # native decoded-media frame clocks are likewise not native-CAD state.
    return (key in OPERATION_NATIVE_FIELDS or key == "partPath" or key in NATIVE_FIT_FIELDS
            or (key.startswith("native") and key not in SOURCE_CLOCK_FIELDS)
            or key.startswith(("camera", "GPU")) or "certificate" in key.lower())


def unknown_state():
    return {"status": "unobservable", "input": None,
            "evidence": "Original source observations retained; no complete current native state is independently measured. Current playback choices belong to explicit chosen-unobserved family packets."}


