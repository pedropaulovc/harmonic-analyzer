# Removed-volume gates on the drafted numeral cuts. The pinned volumes are the
# generator's integration of the drafted stroke outlines (the first layer's
# disjoint drafted outlines agree with their closed form to 1e-4; the 2026
# seat matched every layer to 7e-4 in run 20261024T020813087Z-49ce2da4). Each
# layer's allowance is half the least removal one of its strokes adds, so a
# stroke the DXF import dropped fails its layer; a straight-wall or
# outward-drafted cut removes over twice as much, a missed face nothing. After
# every layer is cut, later layers cover part of some strokes, so the drives
# and the save hold the volume to half the finished part's least stroke.
NUMERAL_LAYER_ALLOWANCES_MM3 = tuple(0.5 * least for least in NUMERAL_LAYER_MIN_STROKE_MM3)
NUMERAL_VOLUME_ALLOWANCE_MM3 = min(NUMERAL_LAYER_ALLOWANCES_MM3)
NUMERAL_FINAL_ALLOWANCE_MM3 = 0.5 * NUMERAL_FINAL_MIN_STROKE_MM3
# Imported sketch vertices land on their DXF's to within this (mm).
NUMERAL_PLACEMENT_TOL_MM = 1e-3


def numeral_feature_names() -> list[str]:
    """One cut per stroke layer: Numerals, Numerals2, ..."""
    return ["Numerals" if i == 0 else f"Numerals{i + 1}" for i in range(len(NUMERAL_LAYER_DXFS))]


def _assert_one_numeral_cut(adapter, name: str) -> bool:
    """Read one native numeral cut's depth and V draft back; returns its
    draft-outward flag (the seat's sense of it is proved by removed volume)."""
    half_angle = NUMERAL_V_INCLUDED_ANGLE_DEG / 2.0
    feature = _early_bound(_feature_by_name(adapter, name), "IFeature")
    definition = feature.GetDefinition()
    if definition is None:
        raise RuntimeError(f"{name}: missing native extrusion definition")
    definition = _early_bound(definition, "IExtrudeFeatureData2")
    depth = float(definition.GetDepth(True)) * 1000.0
    if abs(depth - NUMERAL_DEPTH) > 1e-6:
        raise RuntimeError(f"{name}: expected depth {NUMERAL_DEPTH}; got depth {depth}")
    drafted = bool(definition.GetDraftWhileExtruding(True))
    angle = math.degrees(float(definition.GetDraftAngle(True)))
    if not drafted or abs(angle - half_angle) > 1e-6:
        raise RuntimeError(
            f"{name}: expected a {half_angle:g} deg draft on every wall (a "
            f"{NUMERAL_V_INCLUDED_ANGLE_DEG:g} deg included V); got "
            f"drafted={drafted} angle={angle:.6g}"
        )
    return bool(definition.GetDraftOutward(True))


def _assert_numeral_cut(adapter, proved: bool | None = None) -> bool:
    """Read every native numeral cut's depth and V draft; returns their one
    draft sense. Pass ``proved``, the sense read right after the per-layer
    volumes proved the V inward, to require it after drives and the save."""
    senses = {name: _assert_one_numeral_cut(adapter, name) for name in numeral_feature_names()}
    if len(set(senses.values())) != 1:
        raise RuntimeError(f"numeral cuts disagree on draft direction: {senses}")
    sense = next(iter(senses.values()))
    if proved is not None and sense != proved:
        raise RuntimeError(
            f"numeral draft sense flipped from the volume-proved {proved} to {sense}"
        )
    return sense


# FeatureCut3 forms tried on the first stroke layer, in order. On the 2026
# seat (revision 34), with these imported sketches on the Front plane:
# - single-ended cuts in the default direction return None from FeatureCut3
#   and FeatureCut4 alike: that direction leaves the bar, so nothing is cut;
# - the adapter's double-ended cut (D2 = D1) cuts, but takes no draft at
#   all: 15 deg removed the straight-wall 3.1352 mm^3, 15 deg at 0.10 deep the
#   straight 0.7838 (run 20261023T205133476Z-58eeb077), and a draft added
#   later through ModifyDefinition was ignored too.
# So the V is single-ended in the REVERSED direction, into the bar. Ddir1's
# inward sense is seat-specific (diag_mcmaster_phillips_flat_head: True
# flared). The removed volume, not the flags, decides: the first layer's V is
# pinned to 1e-4 by its closed form, and a flared or straight cut removes 2-3x
# as much. If none cuts, discriminating probes are reported.
V_CUT_VARIANTS = (
    ("single-ended reversed, Ddir1 False", False),
    ("single-ended reversed, Ddir1 True", True),
)


def _v_cut_args(ddir1: bool, *, reverse: bool = True, drafted: bool = True,
                depth_mm: float = NUMERAL_DEPTH) -> tuple:
    """FeatureCut3's 26 arguments for a single-ended blind (V) cut."""
    return (
        True, False, reverse,  # Sd single-ended, Flip, Dir (reversed: into the bar)
        0, 0, depth_mm / 1000.0, 0.0,  # T1/T2 blind, D1, D2
        drafted, False, ddir1, False,  # Dchk1, Dchk2, Ddir1, Ddir2
        math.radians(NUMERAL_V_INCLUDED_ANGLE_DEG / 2.0), 0.0,  # Dang1, Dang2
        False, False, False, False, False,  # offsets, translate, NormalCut
        False, True, False, False, False,  # scope, auto-select, assembly flags
        0, 0.0, False,  # T0 sketch plane, StartOffset, FlipStartOffset
    )


class FeatureCutRefused(RuntimeError):
    """FeatureCut3 returned no feature for this form (a probe may try another)."""


def _feature_cut3(adapter, sketch_name: str, args: tuple) -> object:
    """FeatureCut3 on the named sketch; the feature. Raises RuntimeError if the
    sketch cannot be selected and FeatureCutRefused if the cut is refused."""
    from solidworks_mcp.adapters.pywin32_adapter import null_callout

    model = adapter.currentModel
    model.ClearSelection2(True)
    if not model.Extension.SelectByID2(sketch_name, "SKETCH", 0.0, 0.0, 0.0, False, 0, null_callout(), 0):
        raise RuntimeError(f"select sketch {sketch_name!r} failed")
    feature, error = adapter._attempt_with_error(lambda: model.FeatureManager.FeatureCut3(*args))
    model.ClearSelection2(True)
    if not feature:
        raise FeatureCutRefused(f"FeatureCut3 returned None ({error})")
    return feature


async def _try_cut(adapter, sketch_name: str, args: tuple) -> str:
    """Diagnostic: make one cut, report what it removed, and undo it."""
    pre = await _volume_mm3(adapter)
    try:
        _feature_cut3(adapter, sketch_name, args)
    except Exception as exc:  # noqa: BLE001 - a diagnostic reports, never raises
        result = str(exc)
    else:
        try:
            removed = pre - await _volume_mm3(adapter)
        finally:  # undo the probe even if the measurement fails
            adapter.currentModel.EditUndo2(1)
        result = f"created, removed {removed:.4f} mm^3"
    _telemetry.info(f"V cut probe on {sketch_name}: {result}")
    return result


async def _first_v_cut(adapter, sketch_name: str, pre: float) -> tuple:
    """Find the form that removes exactly the first layer's V; undo the rest.
    ``pre`` is the volume before the cut."""
    tried = []
    for label, ddir1 in V_CUT_VARIANTS:
        args = _v_cut_args(ddir1)
        try:
            _feature_cut3(adapter, sketch_name, args)
        except FeatureCutRefused as exc:
            tried.append(f"{label}: {exc}")
            continue
        removed = pre - await _volume_mm3(adapter)
        expected = NUMERAL_LAYER_VOLUMES_MM3[0]
        if abs(removed - expected) <= NUMERAL_LAYER_ALLOWANCES_MM3[0]:
            _telemetry.info(f"V cut form: {label} removed {removed:.4f} mm^3 (pinned {expected:.4f})")
            return args
        tried.append(f"{label}: removed {removed:.4f} mm^3")
        adapter.currentModel.EditUndo2(1)
        restored = pre - await _volume_mm3(adapter)
        if abs(restored) > 1e-6:
            raise RuntimeError(f"undo of the {label} V cut left {restored:.4f} mm^3 removed; tried {tried}")
    # Discriminate the refusal: undrafted single-ended controls in each
    # direction say whether the direction or the draft is refused.
    probes = {
        "undrafted reversed": _v_cut_args(False, drafted=False),
        "undrafted default direction": _v_cut_args(False, reverse=False, drafted=False),
    }
    for label, args in probes.items():
        tried.append(f"probe {label}: {await _try_cut(adapter, sketch_name, args)}")
    raise RuntimeError(
        f"no FeatureCut3 form removed the first layer's {NUMERAL_LAYER_VOLUMES_MM3[0]:.4f} mm^3 V: "
        + "; ".join(tried)
    )


@_telemetry.traced("cut.ms_stick_numerals", label_param="name")
async def _cut_numerals(adapter, drive_jobs: list[tuple[str, str]], name: str, args: tuple | None,
                        pre: float) -> tuple:
    """Blind V cut of one imported stroke layer, read back at once; returns
    the FeatureCut3 form, found on the first layer (from ``pre``, the volume
    before the cut) and reused after it."""
    sketch = f"{name}Sketch"
    if args is None:
        args = await _first_v_cut(adapter, sketch, pre)
    else:
        try:
            _feature_cut3(adapter, sketch, args)
        except FeatureCutRefused as exc:
            raise RuntimeError(f"{name}: {exc}") from exc
    name_last_feature(adapter, name)
    # D1 is the direction-1 blind depth (D2 repeats it for the unused second
    # direction, as on the adapter's cut); the draft adds an angle dimension.
    rows = dump_dimensions(adapter, name)
    depth_rows = [row["index"] for row in rows
                  if str(row["full_name"]).startswith("D1@") and abs(row["value_mm"] - NUMERAL_DEPTH) < 1e-6]
    if len(depth_rows) != 1:
        raise RuntimeError(f"{name}: expected D1 reading {NUMERAL_DEPTH} mm, found {rows}")
    name_dimensions(adapter, name, [None] * depth_rows[0] + ["NumeralDepth"])
    drive_jobs.append((f"NumeralDepth@{name}", '"NumeralDepth"'))
    _assert_one_numeral_cut(adapter, name)
    return args


def _min_limit(adapter, feature: str, name: str) -> None:
    """``name`` as the single limit "n.nn MIN" (swTolMIN prints the nominal
    plus MIN), read back; the model value is the printed minimum."""
    lower, upper = MIN_LIMIT_DEVIATIONS_MM[name]
    limit = DRAWING_VALUES_BY_NAME[name]
    _, dimension = _named_dimension(adapter, feature, name)
    value = float(dimension.SystemValue)
    if not math.isclose(value, limit / 1000.0, abs_tol=1e-9):
        raise RuntimeError(f"{name}@{feature}: nominal {value * 1000.0:.7f} is not the limit {limit}")
    tolerance = _early_bound(dimension.Tolerance, "IDimensionTolerance")
    tolerance.Type = MIN_LIMIT_TOL_TYPE
    if not tolerance.SetValues(lower / 1000.0, upper / 1000.0):
        raise RuntimeError(f"{name}@{feature}: SetValues rejected {lower:+g}/{upper:+g} mm")
    if (
        int(tolerance.Type) != MIN_LIMIT_TOL_TYPE
        or not math.isclose(float(tolerance.GetMinValue()), lower / 1000.0, abs_tol=1e-12)
        or not math.isclose(float(tolerance.GetMaxValue()), upper / 1000.0, abs_tol=1e-12)
    ):
        raise RuntimeError(f"{name}@{feature}: MIN-limit tolerance readback changed")
    _telemetry.success(f"{name}@{feature}: {float(dimension.SystemValue) * 1000.0:.2f} MIN")


async def _volume_mm3(adapter) -> float:
    mass = await adapter.get_mass_properties()
    if not mass.is_success:
        raise RuntimeError(f"measuring stick: get_mass_properties failed: {mass.error}")
    volume = float(mass.data.volume)
    if not math.isfinite(volume):
        raise RuntimeError(f"measuring stick: get_mass_properties returned volume {volume!r}")
    return volume


def _check_numeral_volume(label: str, removed: float, expected: float, allowance: float) -> None:
    _telemetry.info(f"{label}: V cut removed {removed:.4f} mm^3 (pinned {expected:.4f})")
    if not math.isfinite(removed) or abs(removed - expected) > allowance:
        raise RuntimeError(
            f"{label}: V cut removed {removed:.4f} mm^3, expected {expected:.4f} "
            f"+/-{allowance:.4f} -- check for a dropped stroke, the draft direction, "
            "the DXF import plane/placement, or re-pin the volumes from the generator"
        )


async def _check_volume_unchanged(adapter, label: str, built: float) -> None:
    """The volume still reads ``built`` to half the finished part's least
    stroke, so a rebuild or save that loses one stroke fails here."""
    volume = await _volume_mm3(adapter)
    _telemetry.info(f"{label}: volume {volume:.4f} mm^3 (as built {built:.4f})")
    if abs(volume - built) > NUMERAL_FINAL_ALLOWANCE_MM3:
        raise RuntimeError(
            f"{label}: volume {volume:.4f} mm^3 moved from the as-built {built:.4f} by more "
            f"than {NUMERAL_FINAL_ALLOWANCE_MM3:.4f} -- a drive or the save changed the geometry"
        )


def _dxf_bbox(path) -> tuple[float, float, float, float]:
    return dxf.bbox([ring for ring, _closed in dxf.read_lwpolylines(path.read_text(encoding="ascii"))])


def _sketch_to_model(values: tuple[float, ...], xyz: tuple[float, float, float]) -> tuple[float, float, float]:
    """Apply IMathTransform ArrayData (row-vector rotation, translation, scale;
    the draw_fr_frame_assembly convention) to one point, in metres."""
    x, y, z = xyz
    scale = values[12]
    return (
        scale * (x * values[0] + y * values[3] + z * values[6]) + values[9],
        scale * (x * values[1] + y * values[4] + z * values[7]) + values[10],
        scale * (x * values[2] + y * values[5] + z * values[8]) + values[11],
    )


@_telemetry.traced("check.ms_stick_layer_placement", label_param="sketch_name")
def _assert_layer_placement(adapter, sketch_name: str, path) -> None:
    """The imported layer sits where its DXF puts it. Removed volume cannot
    see a common shift of every layer, which would move the numerals off the
    gaps the drawing dimensions, so the sketch's own vertices are read back.
    The sketch-to-model transform is read once and applied locally; one native
    MultiplyTransform cross-checks it on the first vertex."""
    feature = _early_bound(_feature_by_name(adapter, sketch_name), "IFeature")
    sketch = _early_bound(feature.GetSpecificFeature2(), "ISketch")
    inverse = _early_bound(_early_bound(sketch.ModelToSketchTransform, "IMathTransform").Inverse(), "IMathTransform")
    values = tuple(float(value) for value in inverse.ArrayData)
    if len(values) != 16 or not all(map(math.isfinite, values)):
        raise RuntimeError(f"{sketch_name}: sketch-to-model transform is incomplete: {values}")
    local = []
    for raw in sketch.GetSketchPoints2() or ():
        point = _early_bound(raw, "ISketchPoint")
        local.append((float(point.X), float(point.Y), float(point.Z)))
    if not local:
        raise RuntimeError(f"{sketch_name}: the imported sketch has no points")
    utility = _early_bound(adapter.swApp.GetMathUtility(), "IMathUtility")
    native = _early_bound(utility.CreatePoint(double_array(list(local[0]))), "IMathPoint")
    checked = tuple(float(value) for value in _early_bound(native.MultiplyTransform(inverse), "IMathPoint").ArrayData)
    if any(abs(a - b) > 1e-9 for a, b in zip(checked[:3], _sketch_to_model(values, local[0]), strict=True)):
        raise RuntimeError(f"{sketch_name}: local transform {_sketch_to_model(values, local[0])} != native {checked[:3]}")
    got = dxf.bbox([[(x * 1000.0, y * 1000.0) for x, y, _z in (_sketch_to_model(values, p) for p in local)]])
    want = _dxf_bbox(path)
    _telemetry.info(f"{sketch_name}: {len(local)} points, imported bbox {tuple(round(v, 4) for v in got)} "
                    f"(DXF {tuple(round(v, 4) for v in want)})")
    if any(abs(a - b) > NUMERAL_PLACEMENT_TOL_MM for a, b in zip(got, want, strict=True)):
        raise RuntimeError(f"{sketch_name}: imported at {got}, but {path.name} places it at {want}")


@_telemetry.traced("dim.ms_stick_text")
def author_dimension_callouts(adapter) -> None:
    """Write each callout below its source dimension and read it back: the
    drawing imports this text and never sets it (#1942)."""
    by_feature: dict[str, dict[str, str]] = {}
    for name, text in callouts.CALLOUTS.items():
        by_feature.setdefault(callouts.FEATURE_OF[name], {})[name] = text
    for feature, texts in by_feature.items():
        displays = _named_dimensions(adapter, feature, set(texts))
        for name, text in texts.items():
            display, _dimension = displays[name]
            display.SetText(callouts.CALLOUT_BELOW, text)
            printed = str(display.GetText(callouts.CALLOUT_BELOW) or "")
            if callouts.callout_rows(printed) != callouts.callout_rows(text):
                raise RuntimeError(f"{name}@{feature}: callout did not persist: {printed!r}")


async def _cut_tick(
    adapter,
    label: str,
    stem: str,
    x_center: float,
    length: float,
    *,
    drive_jobs: list[tuple[str, str]],
    drive_xcenter: str,
    drive_length: str,
) -> str:
    """Cut one graduation tick; returns the cut feature name.

    Self-naming: ``stem`` makes the sketch/feature/dim names unique per tick
    (the equation manager keys dims by ``leaf@feature``). The four sketch dims
    emit in creation order -- width, length, then the bottom-left corner anchor
    (x then z, both non-zero) -- recorded into a per-tick :class:`SketchDims` and
    driven via the deferred ``drive_jobs`` batch. ``drive_xcenter`` is the
    equation for the tick's centre x; the corner-X dim is an UNSIGNED distance,
    so it drives to that centre minus half the tick width.
    """
    dims = SketchDims()
    check(f"create_sketch {label}", await adapter.create_sketch("Front"))
    half = TICK_WIDTH / 2.0
    top_y = BODY_WIDTH + TICK_OVERHANG
    lines = await add_line_chain(
        adapter,
        [
            (x_center - half, BODY_WIDTH - length),
            (x_center + half, BODY_WIDTH - length),
            (x_center + half, top_y),
            (x_center - half, top_y),
        ],
    )
    bottom, right, top, left = lines
    for ent, relation in (
        (bottom, "horizontal"),
        (top, "horizontal"),
        (right, "vertical"),
        (left, "vertical"),
    ):
        check(
            f"{label} constraint {relation}",
            await adapter.add_sketch_constraint(ent, None, relation),
        )
    check(
        f"{label} width dim",
        await adapter.add_sketch_dimension(bottom, None, "linear", TICK_WIDTH),
    )
    dims.record(f"{stem}Width", '"TickWidth"')
    check(
        f"{label} length dim",
        await adapter.add_sketch_dimension(
            right, None, "linear", length + TICK_OVERHANG
        ),
    )
    dims.record(f"{stem}Length", f'{drive_length} + "TickOverhang"')
    # Corner anchor at (x_center - half, BODY_WIDTH - length): both non-zero, so
    # two dims (x then z). Both are unsigned distances from the origin and both
    # land positive here, so the drives evaluate positive directly.
    await anchor_point_to_origin(
        adapter,
        f"{bottom}.start",
        x_center - half,
        BODY_WIDTH - length,
        f"{label} corner",
    )
    dims.record(f"{stem}CornerX", f'{drive_xcenter} - "TickWidth" / 2')
    dims.record(f"{stem}CornerZ", f'"BodyWidth" - ({drive_length})')
    await ensure_fully_defined(adapter, f"{label} sketch")
    check(f"exit_sketch {label}", await adapter.exit_sketch())
    name_last_feature(adapter, f"{stem}Profile")
    drive_jobs += dims.apply(adapter, f"{stem}Profile")
    # Single-ended into the bar, so the depth dimension spans face to floor;
    # the adapter's double-ended cut put D1 on the air side (detail B, run
    # 20261023T211330900Z-bfdf1b6e: the depth read from a stub above the face).
    cut = _feature_cut3(adapter, f"{stem}Profile", _v_cut_args(False, drafted=False, depth_mm=TICK_DEPTH))
    if isinstance(cut, Exception):
        raise RuntimeError(f"cut {label}: {cut}")
    return name_last_feature(adapter, f"{stem}Cut")


@_telemetry.traced("sketch.stick_manufacturing_chords")
async def _manufacturing_chords(adapter, drive_jobs: list[tuple[str, str]]) -> None:
    """Bind finished engraving sizes to their knobs, excluding profile overhang.

    The tracked numeral artwork stays fixed. Its gaps therefore measure from
    the editable tick to the original glyph edge, not to an imaginary moved DXF.
    """
    scale_x = '"ScaleStartX"'
    edge_y = '"BodyWidth"'
    glyph_x = SCALE_START_X + TICK_WIDTH / 2.0 + NUMERAL_GAP_MM
    glyph_y = BODY_WIDTH - TICK_LENGTH - NUMERAL_GAP_MM
    bindings = {
        "ScaleStartReference": (scale_x, None, edge_y),
        "FullLengthReference": ('"TickLength"', scale_x, '"BodyWidth" - "TickLength"'),
        "MinorLengthReference": (
            '"MinorTickLength"',
            f'{scale_x} + "DivisionSpacing" / {MINOR_PER_DIVISION}',
            '"BodyWidth" - "MinorTickLength"',
        ),
        "HalfLengthReference": (
            '"HalfTickLength"', f'{scale_x} + "DivisionSpacing" / 2',
            '"BodyWidth" - "HalfTickLength"',
        ),
        "FullPitchReference": ('"DivisionSpacing"', scale_x, edge_y),
        "MinorPitchReference": (
            f'"DivisionSpacing" / {MINOR_PER_DIVISION}', scale_x, edge_y,
        ),
        "NumeralHeightReference": (
            f"{NUMERAL_HEIGHT_MM}mm", f"{glyph_x}mm", f"{glyph_y}mm",
        ),
        "NumeralXGapReference": (
            f'{glyph_x}mm - ({scale_x} + "TickWidth" / 2)',
            f'{scale_x} + "TickWidth" / 2', f"{glyph_y}mm",
        ),
        "NumeralYGapReference": (
            f'"BodyWidth" - "TickLength" - {glyph_y}mm',
            f"{glyph_x}mm", f"{glyph_y}mm",
        ),
    }
    for feature, (name, start, end) in REFERENCE_DIMENSIONS.items():
        dims = SketchDims()
        size_expr, x_expr, y_expr = bindings[feature]
        check(feature, await adapter.create_sketch("Front"))
        set_sketch_direct_db(adapter, True)
        line = check(feature, await adapter.add_line(*start, *end))
        set_sketch_direct_db(adapter, False)
        segment = _early_bound(adapter._sketch_entities[line], "ISketchSegment")
        segment.ConstructionGeometry = True
        if not bool(segment.ConstructionGeometry):
            raise RuntimeError(f"{feature}: construction flag rejected")
        horizontal = start[1] == end[1]
        check(feature, await adapter.add_sketch_constraint(
            line, None, "horizontal" if horizontal else "vertical"))
        await dimension_between(
            adapter, f"{line}.start", f"{line}.end",
            "horizontal_distance" if horizontal else "vertical_distance",
            abs(end[0] - start[0]) if horizontal else abs(end[1] - start[1]),
            feature,
        )
        dims.record(name, size_expr)
        await anchor_point_to_origin(adapter, f"{line}.start", *start, feature)
        if abs(start[0]) >= 1e-9:
            dims.record(f"{name}AnchorX", x_expr)
        if abs(start[1]) >= 1e-9:
            dims.record(f"{name}AnchorY", y_expr)
        await ensure_fully_defined(adapter, feature)
        check(feature, await adapter.exit_sketch())
        name_last_feature(adapter, feature)
        drive_jobs += dims.apply(adapter, feature)


@_telemetry.traced("appearance.stick_manufacturing_chords")
def _hide_manufacturing_chords(adapter) -> None:
    model = _early_bound(adapter.currentModel, "IPartDoc")
    for feature_name in REFERENCE_DIMENSIONS:
        feature = model.FeatureByName(feature_name)
        if feature is None:
            raise RuntimeError(f"missing manufacturing sketch {feature_name}")
        blank_sketch_feature(adapter.currentModel, _early_bound(feature, "IFeature"), feature_name)


async def build(adapter) -> dict[str, str]:
    from solidworks_mcp.adapters.base import (
        ExtrusionParameters,
        ImportDxfDwgParameters,
        LinearPatternParameters,
    )

    check("create_part", await adapter.create_part())

    # Editable knobs (Tools > Equations). The mm suffix is load-bearing -- this is
    # an INCH document and the equation manager reads BARE numbers in document
    # units (an unsuffixed 200 = 200 in, a 25.4x blow-up). ScaleStartX is a
    # DERIVED global (locates the configured scale short of the right end),
    # referencing the others as an equation string. DivisionSpacing drives the
    # FEATURE parameter -- a knob with nothing in the deferred sketch-dim batch,
    # like an extrude depth (matches the exemplars).
    await set_global(adapter, "BodyLength", f"{BODY_LENGTH}mm")
    await set_global(adapter, "BodyWidth", f"{BODY_WIDTH}mm")
    await set_global(adapter, "BodyThickness", f"{BODY_THICKNESS}mm")
    await set_global(adapter, "DivisionSpacing", f"{DIVISION_SPACING}mm")
    await set_global(adapter, "ScaleEndMargin", f"{SCALE_END_MARGIN}mm")
    await set_global(adapter, "TickWidth", f"{TICK_WIDTH}mm")
    await set_global(adapter, "TickLength", f"{TICK_LENGTH}mm")
    await set_global(adapter, "MinorTickLength", f"{MINOR_TICK_LENGTH}mm")
    await set_global(adapter, "HalfTickLength", f"{HALF_TICK_LENGTH}mm")
    await set_global(adapter, "TickOverhang", f"{TICK_OVERHANG}mm")
    await set_global(adapter, "NumeralDepth", f"{NUMERAL_DEPTH}mm")
    await set_global(
        adapter,
        "ScaleStartX",
        f'"BodyLength" - {DIVISION_COUNT - 1} * "DivisionSpacing" - "ScaleEndMargin"',
    )

    drive_jobs: list[tuple[str, str]] = []

    # Body: plain rectangular bar. Two display dims emit in creation order --
    # length then width -- recorded as they are added; the (0, 0) corner anchors
    # by a coincident relation (no dim).
    body_dims = SketchDims()
    check("create_sketch body", await adapter.create_sketch("Front"))
    body = await add_line_chain(
        adapter,
        [(0.0, 0.0), (BODY_LENGTH, 0.0), (BODY_LENGTH, BODY_WIDTH), (0.0, BODY_WIDTH)],
    )
    bottom, right, top, left = body
    for ent, relation in (
        (bottom, "horizontal"),
        (top, "horizontal"),
        (right, "vertical"),
        (left, "vertical"),
    ):
        check(
            f"body constraint {relation}",
            await adapter.add_sketch_constraint(ent, None, relation),
        )
    check(
        "body length dim",
        await adapter.add_sketch_dimension(bottom, None, "linear", BODY_LENGTH),
    )
    body_dims.record("BodyLength", '"BodyLength"')
    check(
        "body width dim",
        await adapter.add_sketch_dimension(right, None, "linear", BODY_WIDTH),
    )
    body_dims.record("BodyWidth", '"BodyWidth"')
    # Pin the (0, 0) corner to the origin. The h/v relations + the two dims fix
    # the bar's shape but not its position; that corner was previously located
    # only by SolidWorks snapping it onto the origin during the (inference-on)
    # line draw -- a crutch removed now that add_line_chain suppresses inference.
    check(
        "body corner -> origin",
        await adapter.add_sketch_constraint(f"{bottom}.start", "origin", "coincident"),
    )
    await ensure_fully_defined(adapter, "body sketch")
    check("exit_sketch body", await adapter.exit_sketch())
    name_last_feature(adapter, "BodyProfile")
    drive_jobs += body_dims.apply(adapter, "BodyProfile")
    check(
        "extrude body",
        await adapter.create_extrusion(ExtrusionParameters(depth=BODY_THICKNESS)),
    )
    name_last_feature(adapter, "Body")
    # Drive the body's extrude depth from BodyThickness too (D1 is the blind-
    # extrude depth dim) so the thickness knob is live, not inert. As-built ->
    # neutral.
    name_dimensions(adapter, "Body", ["BodyThickness"])
    drive_jobs.append(("BodyThickness@Body", '"BodyThickness"'))

    # Tick 0 (seed) + linear pattern for ticks 1..10. The seed cut is RENAMED
    # ("Tick0Cut"), so the pattern must seed off the NEW name -- a captured
    # auto-name would go stale the moment name_last_feature ran (M: renamed-feature
    # references). _cut_tick returns the assigned name for exactly this reason.
    seed_name = await _cut_tick(
        adapter,
        "tick 0",
        "Tick0",
        SCALE_START_X,
        TICK_LENGTH,
        drive_jobs=drive_jobs,
        drive_xcenter='"ScaleStartX"',
        drive_length='"TickLength"',
    )
    name_dimensions(adapter, "Tick0Cut", ["TickDepth"])
    check(
        "linear pattern ticks 1..10",
        await adapter.linear_pattern_feature(
            LinearPatternParameters(
                direction_point=[BODY_LENGTH / 2.0, 0.0, 0.0],
                direction_vector=[1.0, 0.0, 0.0],
                features=[seed_name],
                count=DIVISION_COUNT,
                spacing=DIVISION_SPACING,
            )
        ),
    )
    name_last_feature(adapter, "TickPattern")
    # Drive the pattern's spacing from DivisionSpacing too. The seed (Tick0) and
    # half-tick are driven from ScaleStartX (DivisionSpacing-derived), so the
    # pattern's own spacing dim MUST track DivisionSpacing or ticks 1..10 keep
    # the old 8 mm pitch and the ruled scale corrupts on a GUI edit (the Codex
    # P2). The spacing is D3 (verified by dump_dimensions: D1 is the pattern's
    # ~11000 mm direction-reference length, NOT the pitch); D3 == as-built 8 mm,
    # so it stays neutral.
    drive_jobs.append(("D3@TickPattern", '"DivisionSpacing"'))

    # Tenths: nine short ticks between the 0 and 1 full ticks, cut one by one
    # (each drives off ScaleStartX + k * DivisionSpacing / 10), then the nine
    # patterned as a group across the other nine divisions. (A pattern of the
    # minor pattern would need two nested pattern features; nine seed cuts +
    # one pattern keeps every feature a plain cut or pattern.) The pattern's
    # own spacing dim is driven from DivisionSpacing below, resolved by VALUE
    # rather than by the D3 index (CodeRabbit #651: a static pitch would
    # leave the patterned tenths at 14.2 after a GUI DivisionSpacing edit).
    minor_names = []
    for k in range(1, MINOR_PER_DIVISION):
        minor_names.append(
            await _cut_tick(
                adapter,
                f"minor tick 0.{k}",
                f"Minor{k}",
                SCALE_START_X + k * MINOR_SPACING,
                MINOR_TICK_LENGTH,
                drive_jobs=drive_jobs,
                drive_xcenter=f'"ScaleStartX" + {k} * "DivisionSpacing" / {MINOR_PER_DIVISION}',
                drive_length='"MinorTickLength"',
            )
        )
    check(
        "linear pattern minor ticks across divisions 1..9",
        await adapter.linear_pattern_feature(
            LinearPatternParameters(
                direction_point=[BODY_LENGTH / 2.0, 0.0, 0.0],
                direction_vector=[1.0, 0.0, 0.0],
                features=minor_names,
                count=DIVISION_COUNT - 1,
                spacing=DIVISION_SPACING,
            )
        ),
    )
    name_last_feature(adapter, "MinorPattern")
    # The pattern's dims are the direction-reference length (~11000 mm), the
    # count and the pitch; the one reading the as-built pitch is unambiguous.
    minor_pitch_dims = [
        row["full_name"]
        for row in dump_dimensions(adapter, "MinorPattern")
        if abs(row["value_mm"] - DIVISION_SPACING) < 1e-3
    ]
    if len(minor_pitch_dims) != 1:
        raise RuntimeError(
            f"MinorPattern: expected one dim reading the {DIVISION_SPACING} pitch, "
            f"found {minor_pitch_dims}"
        )
    drive_jobs.append((minor_pitch_dims[0], '"DivisionSpacing"'))

    # The hand-stamped artefact the book calls out: a longer 0.5 tick (it
    # overcuts the 0.5 tenth above).
    await _cut_tick(
        adapter,
        "tick 0.5",
        "TickHalf",
        SCALE_START_X + DIVISION_SPACING / 2.0,
        HALF_TICK_LENGTH,
        drive_jobs=drive_jobs,
        drive_xcenter='"ScaleStartX" + "DivisionSpacing" / 2',
        drive_length='"HalfTickLength"',
    )

    # Numerals 0..10: import each generated stroke layer (closed rectangles at
    # final model mm, already y-inverted to read correctly on the z=0 face seen
    # from -Z -- see gen_ms_stick_numerals_dxf) onto the Front plane at identity
    # placement and V-cut it. The imported outlines stay fixed, while the native
    # NumeralDepth dimensions drive the engraving depth.
    for path in NUMERAL_LAYER_DXFS:
        if not path.is_file():
            raise RuntimeError(f"numerals DXF not found: {path}")
    pre = await _volume_mm3(adapter)
    before = pre  # an imported sketch removes nothing, so this carries over
    cut_form = None  # found (and volume-proved) on the first layer
    for path, name, layer_volume, allowance in zip(
        NUMERAL_LAYER_DXFS, numeral_feature_names(), NUMERAL_LAYER_VOLUMES_MM3,
        NUMERAL_LAYER_ALLOWANCES_MM3, strict=True
    ):
        check(
            f"import {path.name}",
            await adapter.import_dxf_dwg(
                ImportDxfDwgParameters(
                    file_path=str(path),
                    plane="Front",
                    scale=1.0,
                    position=[0.0, 0.0],
                    merge_points=True,  # closed LWPOLYLINEs -> closed regions
                    import_hatch=False,
                    import_dimensions=False,
                    add_constraints=False,
                )
            ),
        )
        name_last_feature(adapter, f"{name}Sketch")
        _assert_layer_placement(adapter, f"{name}Sketch", path)
        cut_form = await _cut_numerals(adapter, drive_jobs, name, cut_form, before)
        after = await _volume_mm3(adapter)
        # Each layer on its own: a stroke dropped from a small later layer
        # hides inside the combined allowance.
        _check_numeral_volume(name, before - after, layer_volume, allowance)
        before = after
    _check_numeral_volume("all numerals", pre - before, NUMERAL_VOLUME_MM3, NUMERAL_VOLUME_ALLOWANCE_MM3)
    numeral_sense = _assert_numeral_cut(adapter)

    await apply_material(adapter, MATERIAL)

    # Capture the as-built volume, then apply the deferred drive equations and
    # re-check: every equation evaluates to the value just built, so the geometry
    # must not move (the neutrality proof). It holds to the tightest numeral
    # allowance, so a stroke that a later rebuild or the save loses still fails.
    v_built = await _volume_mm3(adapter)
    await _manufacturing_chords(adapter, drive_jobs)
    await force_rebuild(adapter)
    for dim_name, expr in drive_jobs:
        await drive_dimension(adapter, dim_name, expr)
    await force_rebuild(adapter)
    _assert_numeral_cut(adapter, numeral_sense)
    await _check_volume_unchanged(adapter, "driven measuring-stick (equations neutral)", v_built)

    # Verify the 202 mm length and the untouched front face
    # (the 14.2 mm tick spacing is driven by the linear pattern's spacing).
    # End faces are edge-on in the active view (point picking is
    # screen-projected) — measure the uncut front-bottom edge instead;
    # the ticks only engrave the back face from the top edge down.
    mid_y = BODY_WIDTH / 2.0
    await measure_check(
        adapter,
        "body length (202, 2026-10-23 ruling)",
        [{"entity_type": "EDGE", "point": [BODY_LENGTH / 2.0, 0.0, BODY_THICKNESS]}],
        "length",
        BODY_LENGTH,
    )
    await measure_check(
        adapter,
        "front face area (ticks cut the back face only)",
        [
            {
                "entity_type": "FACE",
                "point": [BODY_LENGTH / 2.0, mid_y, BODY_THICKNESS],
            }
        ],
        "area",
        BODY_LENGTH * BODY_WIDTH,
        tol=1.0,
    )

    await report_mass_properties(adapter)
    for feature, names in DRAWING_DIMENSIONS.items():
        for name in names:
            if name in DRAWING_TOLERANCES:
                set_dimension_symmetric_tolerance(
                    adapter, feature, name, DRAWING_TOLERANCES[name])
            if name in MIN_LIMIT_DEVIATIONS_MM:
                _min_limit(adapter, feature, name)
    clear_dimensions_for_drawing(adapter)
    for feature_name, dimension_names in DRAWING_DIMENSIONS.items():
        mark_dimensions_for_drawing(adapter, feature_name, dimension_names)
    author_dimension_callouts(adapter)
    apply_drawing_precision(adapter, DRAWING_PRECISION)
    apply_drawing_properties(
        adapter,
        PART_NAME,
        {
            "Manufacturing Notes": DRAWING_NOTES,
            "Front View Note": FRONT_VIEW_NOTE,
            "Isometric View Note": ISOMETRIC_VIEW_NOTE,
            "Numeral Placement Note": NUMERAL_PLACEMENT_NOTE,
        },
    )
    _hide_manufacturing_chords(adapter)
    outputs = await save_part_and_images(adapter, PART_NAME)
    _assert_numeral_cut(adapter, numeral_sense)
    await _check_volume_unchanged(adapter, "saved measuring-stick", v_built)
    return outputs


if __name__ == "__main__":
    sys.exit(run_build(build))
