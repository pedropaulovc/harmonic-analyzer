@pytest.mark.parametrize("mutation", ["number", "configuration", "prior_stem", "neutral", "nonshared"])
def test_actual_conflicting_map_identities_are_rejected(tmp_path, mutation):
    payload = json.loads(IDENTITY_MAP.read_text(encoding="utf-8"))
    shared = [identity for row in payload["parts_and_assemblies"]
              for identity in row["new_identities"] if "prior_stem" in identity]
    if mutation == "number":
        shared[0]["number"] = "MHA-CONFLICT-00"
    elif mutation == "configuration":
        shared[0]["configuration"] = "Inner"
    elif mutation == "prior_stem":
        # Distinct members cannot claim the same previous native identity.
        chain = [identity for identity in shared if identity["stem"] == "sh-vn-chain-link"]
        chain[1]["prior_stem"] = chain[0]["prior_stem"]
    elif mutation == "neutral":
        payload["shared_vendor_groups"][0]["neutral_export_configuration"] = "Default"
    else:
        ordinary = [row for row in payload["parts_and_assemblies"]
                    if all("prior_stem" not in identity for identity in row["new_identities"])]
        ordinary[1]["new_identities"] = ordinary[0]["new_identities"]
    current = tmp_path / "current.json"
    current.write_text(json.dumps(payload), encoding="utf-8")
    with pytest.raises(ValueError, match="conflict|duplicate|current identity"):
        load_identity_map(current)


