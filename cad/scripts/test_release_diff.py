@pytest.mark.parametrize("parts", ["pd-vn-chain-outer-link", "chain-outer-link", "sh-vn-chain-link--OuterLink"])
def test_release_cli_inventories_configured_stl_without_step_and_explicitly_skips_boolean(
    tmp_path, monkeypatch, capsys, parts,
):
    import release_diff

    old = {"step/pd-vn-chain-outer-link.STEP": {"crc": 1, "uncomp": 100},
           "stl/pd-vn-chain-outer-link.STL": {"crc": 2, "uncomp": 50}}
    new = {"step/sh-vn-chain-link.STEP": {"crc": 3, "uncomp": 100},
           "stl/sh-vn-chain-link--outerlink.STL": {"crc": 4, "uncomp": 50}}
    monkeypatch.setattr(release_diff, "central_dir", lambda url: old if "before/" in url else new)
    monkeypatch.setattr(release_diff, "CACHE", tmp_path)
    extracted, compared = [], []
    monkeypatch.setattr(release_diff, "extract", lambda url, entry, dest: extracted.append(dest))
    result = dict(hausdorff_mm=0, mean_dev_mm=0, vol_a_mm3=1, vol_b_mm3=1,
                  tris_a=12, tris_b=12, bbox_a=[1, 1, 1], bbox_b=[1, 1, 1])
    monkeypatch.setattr(release_diff, "mesh_deviation", lambda *args: compared.append(args) or result)
    monkeypatch.setattr(release_diff, "boolean_cut", lambda *args: pytest.fail("missing STEP was used"))
    monkeypatch.setattr(sys, "argv", ["release_diff.py", "before", "after", "--parts", parts])
    release_diff.main()
    output = capsys.readouterr().out
    assert compared == [("before", "after", "pd-vn-chain-outer-link", "sh-vn-chain-link--outerlink")]
    assert "(3c) mesh:" in output and "IDENTICAL (within mesh tol)" in output
    assert "(3b) solid:   SKIPPED (member missing from a bundle)" in output
    assert tmp_path / "after" / "sh-vn-chain-link.step" not in extracted


